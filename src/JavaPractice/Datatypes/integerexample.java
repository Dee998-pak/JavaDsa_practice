package JavaPractice.Datatypes;

public class integerexample {
    public static void main(String[] args){

        int age  = 27;
        int mark =  421;
        int yr   =   2025;
        int pin  = 754141;


        int a   =   9999;
        int b   =   8888;
        int c   =   7777;
        int sum =   a+b+c;
        int dif =   a-b-c;
        int mul =   a*b*c;
        int div =   a/b/c;
        int mod =   a%b%c;

        System.out.println("Age:"+age);
        System.out.println("MARK:"+mark);
        System.out.println("YEAR:"+yr);
        System.out.println("PIN:"+pin);
        System.out.println();


        System.out.println("SUM of Three becomes:"+sum);
        System.out.println("Difference Of Three Becomes:"+dif);
        System.out.println("Multiplication Of Three Becomes:"+mul);
        System.out.println("Division of Three becomes:"+div);
        System.out.println("Modulus of Three Becomes:"+mod);

        System.out.println();


        int apple   =   34;
        int orange  =   54;
        int grapes  =   30;
        int total   = apple+orange+grapes;
        System.out.println("Total Fruits Weight Becomes:"+total);


    }
}
