package JavaPractice.Datatypes;

public class ImplicitTypeCasting {
    public static void main(String[] args){
        // 1. byte to short
        byte a = 10;
        short b = a;
        System.out.println("byte to short: " + b);

        // 2. byte to int
        byte c = 20;
        int d = c;
        System.out.println("byte to int: " + d);

        // 3. byte to long
        byte e = 30;
        long f = e;
        System.out.println("byte to long: " + f);

        // 4. byte to float
        byte g = 40;
        float h = g;
        System.out.println("byte to float: " + h);

        // 5. byte to double
        byte i = 50;
        double j = i;
        System.out.println("byte to double: " + j);

        // 6. short to int
        short k = 100;
        int l = k;
        System.out.println("short to int: " + l);

        // 7. short to long
        short m = 200;
        long n = m;
        System.out.println("short to long: " + n);

        // 8. short to float
        short o = 300;
        float p = o;
        System.out.println("short to float: " + p);

        // 9. short to double
        short q = 400;
        double r = q;
        System.out.println("short to double: " + r);

        // 10. char to int
        char s = 'A';
        int t = s;
        System.out.println("char to int: " + t);

        // 11. char to long
        char u = 'B';
        long v = u;
        System.out.println("char to long: " + v);

        // 12. char to float
        char w = 'C';
        float x = w;
        System.out.println("char to float: " + x);

        // 13. char to double
        char y = 'D';
        double z = y;
        System.out.println("char to double: " + z);

        // 14. int to long
        int aa = 500;
        long bb = aa;
        System.out.println("int to long: " + bb);

        // 15. int to float
        int cc = 600;
        float dd = cc;
        System.out.println("int to float: " + dd);

        // 16. int to double
        int ee = 700;
        double ff = ee;
        System.out.println("int to double: " + ff);

        // 17. long to float
        long gg = 800;
        float hh = gg;
        System.out.println("long to float: " + hh);

        // 18. long to double
        long ii = 900;
        double jj = ii;
        System.out.println("long to double: " + jj);

        // 19. float to double
        float kk = 10.5f;
        double ll = kk;
        System.out.println("float to double: " + ll);
    }
}
