package JavaPractice.Operators;

public class Relational {
    public static void main(String[] args){

        int x   =   10,y    =   5;

        System.out.println(x    ==   y);
        System.out.println(x    >   y);
        System.out.println(y    <   x);
        System.out.println(x    >=  y);
        System.out.println(x    <=  y);
    }
}
