package JavaPractice.Operators;

public class Q9MultipleShiftOperations {
        public static void main(String[] args){
            int o   =   64;
            System.out.println(o    <<  1);
            System.out.println(o    >>  2);
            System.out.println(o    >>  1);
            System.out.println(o    <<  2);
            System.out.println(o    <<  3);
        }

}
