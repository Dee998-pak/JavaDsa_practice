package JavaPractice.Operators;

public class OperatorPrecedence {
    public static void main(String[] args){

        int a   =   10, b   =   20, c   =   30, d   =   40, e   =   15;

        int result  =   a   +   b   -   c   *   d   /   e;

        System.out.println("Precedence:"+result);
    }
}
