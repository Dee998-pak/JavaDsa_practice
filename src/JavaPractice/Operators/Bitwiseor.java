package JavaPractice.Operators;

public class Bitwiseor {
    public static void  main(String[] args){
        int x   =   3,  y   =   6;
        int x1  =   21, y1  =   7;
        int x2  =   14, y2  =   12;

        System.out.println(x    |   y);
        System.out.println(x1   |   y1);
        System.out.println(x2   |   y2);
    }
}
